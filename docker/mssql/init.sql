-- Variables sqlcmd : $(WC_DB) $(WC_USER) $(WC_PASS)
USE [master]
IF DB_ID(N'$(WC_DB)') IS NULL
    CREATE DATABASE [$(WC_DB)] COLLATE SQL_Latin1_General_CP1_CI_AS;
GO

ALTER DATABASE [$(WC_DB)] SET ALLOW_SNAPSHOT_ISOLATION ON;
ALTER DATABASE [$(WC_DB)] SET READ_COMMITTED_SNAPSHOT ON WITH ROLLBACK IMMEDIATE;
GO

IF NOT EXISTS (SELECT 1 FROM sys.server_principals WHERE name = N'$(WC_USER)')
    CREATE LOGIN [$(WC_USER)] WITH PASSWORD = N'$(WC_PASS)', DEFAULT_DATABASE=[wind], CHECK_EXPIRATION=OFF, CHECK_POLICY=OFF;
GO

USE [$(WC_DB)];
GO
IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = N'$(WC_USER)')
    CREATE USER [$(WC_USER)] FOR LOGIN [$(WC_USER)] WITH DEFAULT_SCHEMA = dbo;
ALTER ROLE db_owner ADD MEMBER [$(WC_USER)];
GO

use master
GO
sp_configure 'contained database authentication', 1;
GO
RECONFIGURE
GO

USE [master]
GO
CREATE LOGIN [wind] WITH PASSWORD=N'wind', DEFAULT_DATABASE=[wind], CHECK_EXPIRATION=OFF, CHECK_POLICY=OFF
GO
USE [wind]
GO
CREATE USER [wind] FOR LOGIN [wind]
GO
EXEC sp_addrolemember N'db_owner', N'wind'
GO
CREATE SCHEMA [wind] AUTHORIZATION [wind]
GO
ALTER USER [wind] WITH DEFAULT_SCHEMA=[wind]
GO
